function chiudiModalSvuotaDispensa() {
    const modal = document.getElementById('modal-svuota-dispensa');
    if (modal) modal.remove();
}

function confermaESvuotaDispensaDefinitivo() {
    try {
        const datiAttuali = {};
        for (let i = 0; i < localStorage.length; i++) {
            const chiave = localStorage.key(i);
            datiAttuali[chiave] = localStorage.getItem(chiave);
        }
        localStorage.setItem('eat_bef_backup_sicurezza', JSON.stringify(datiAttuali));

        const linguaSalvata = localStorage.getItem('eat_me_first_lang');
        const terminiAccettati = localStorage.getItem('termini_accettati');

        localStorage.clear();

        if (linguaSalvata) localStorage.setItem('eat_me_first_lang', linguaSalvata);
        if (terminiAccettati) localStorage.setItem('termini_accettati', terminiAccettati);

        chiudiModalSvuotaDispensa();

        alert("Dispensa svuotata con successo. Salvato un punto di ripristino di sicurezza interno.");
        location.reload();

    } catch (error) {
        alert("Errore durante l'operazione di reset. Riprova.");
        console.error(error);
    }
}

